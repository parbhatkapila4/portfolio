import { mkdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(root, "src/assets/hero/backdrop.jpg");
const OUT_DIR = path.join(root, "public/hero");
const META = path.join(root, "src/assets/hero/backdrop.generated.ts");

const WIDTHS = [1280, 1920, 2560];
const AVIF = { quality: 64, effort: 7, chromaSubsampling: "4:4:4" };
const WEBP = { quality: 82, effort: 6, smartSubsample: true };

const kb = (n) => `${(n / 1024).toFixed(1)} KB`;

await mkdir(OUT_DIR, { recursive: true });

const source = sharp(SRC);
const meta = await source.metadata();
console.log(
  `source  ${path.relative(root, SRC)}  ${meta.format} ${meta.width}x${meta.height}  ${kb((await stat(SRC)).size)}`,
);

const results = [];
for (const width of WIDTHS) {
  const base = sharp(SRC).resize({ width, withoutEnlargement: true });
  const avifPath = path.join(OUT_DIR, `backdrop-${width}.avif`);
  const webpPath = path.join(OUT_DIR, `backdrop-${width}.webp`);
  await base.clone().avif(AVIF).toFile(avifPath);
  await base.clone().webp(WEBP).toFile(webpPath);
  const [a, w] = await Promise.all([stat(avifPath), stat(webpPath)]);
  const info = await sharp(avifPath).metadata();
  results.push({ width, height: info.height, avif: a.size, webp: w.size });
  console.log(
    `${width}w  ${info.width}x${info.height}  avif ${kb(a.size)}  webp ${kb(w.size)}`,
  );
}
const blur = await sharp(SRC)
  .resize({ width: 16 })
  .jpeg({ quality: 70 })
  .toBuffer();
const blurDataURL = `data:image/jpeg;base64,${blur.toString("base64")}`;

const ts = `// Generated by scripts/optimize-hero.mjs - do not edit by hand.
// Source: src/assets/hero/backdrop.jpg (${meta.width}x${meta.height})
export const heroBackdrop = {
  widths: ${JSON.stringify(WIDTHS)} as const,
  width: ${meta.width},
  height: ${meta.height},
  blurDataURL:
    "${blurDataURL}",
} as const;
`;
await writeFile(META, ts);
console.log(`meta    ${path.relative(root, META)}  blur ${blur.length} B`);
